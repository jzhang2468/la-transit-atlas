// Generate the data script used when index.html is opened directly from disk.
const {readFileSync, writeFileSync} = require("node:fs");
const {join} = require("node:path");

const directory = join(__dirname, "..", "data");
const paths = {
  context: "context.geojson",
  city: "city.geojson",
  tracts: "tracts.geojson",
  stations: "stations.geojson",
  rail: "rail.geojson",
  buffers: "buffers.geojson",
  rings: "rings.geojson",
  summary: "summary.json",
  commute: "commute.json"
};
const data = Object.fromEntries(Object.entries(paths).map(([name, path]) =>
  [name, JSON.parse(readFileSync(join(directory, path), "utf8"))]));
writeFileSync(join(directory, "standalone.js"),
  "/* Generated by reproduce/build_standalone.cjs. */\nwindow.ATLAS_DATA = " + JSON.stringify(data) + ";\n");

const comparison = JSON.parse(readFileSync(join(directory, "neighborhoods.json"), "utf8"));
writeFileSync(join(directory, "neighborhoods-standalone.js"),
  "/* Generated by reproduce/build_standalone.cjs. */\nwindow.NEIGHBORHOOD_DATA = " + JSON.stringify(comparison) + ";\n");

const renterVehicles = JSON.parse(readFileSync(join(directory, "renter-vehicles.json"), "utf8"));
writeFileSync(join(directory, "renter-vehicles-standalone.js"),
  "/* Generated by reproduce/build_standalone.cjs. */\nwindow.RENTER_VEHICLES_DATA = " + JSON.stringify(renterVehicles) + ";\n");
